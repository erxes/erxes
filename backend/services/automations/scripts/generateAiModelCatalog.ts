// Regenerates src/ai/aiAgent/modelCatalog.generated.ts from models.dev and
// checks the configured defaults and curated picks against it.
// Usage: npx tsx backend/services/automations/scripts/generateAiModelCatalog.ts [api.json]
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import {
  AI_AGENT_PROVIDER_DEFAULT_MODELS,
  AI_AGENT_RECOMMENDED_MODELS,
  AI_AGENT_SUPPORTED_PROVIDERS,
} from '../src/ai/aiAgent/constants';
import type {
  TAiModelCatalog,
  TAiModelCatalogEntry,
} from '../src/ai/aiAgent/modelCatalog';

type TProvider = (typeof AI_AGENT_SUPPORTED_PROVIDERS)[number];

type TModelsDevModel = {
  id: string;
  status?: string;
  tool_call?: boolean;
  reasoning?: boolean;
  release_date?: string;
  modalities?: { output?: string[] };
  limit?: { context?: number };
};

type TModelsDevSource = Record<
  string,
  { models?: Record<string, TModelsDevModel> }
>;

const SOURCE_URL = 'https://models.dev/api.json';
const OUTPUT = resolve(
  __dirname,
  '../src/ai/aiAgent/modelCatalog.generated.ts',
);

// Our provider key -> models.dev provider sources, with id rewrites where the
// gateway expects a different prefix than models.dev publishes.
const SOURCES: Record<
  TProvider,
  { provider: string; rewrite?: (id: string) => string }[]
> = {
  openai: [{ provider: 'openai' }],
  grok: [{ provider: 'xai' }],
  kimi: [{ provider: 'moonshotai' }],
  'kimi-code': [{ provider: 'kimi-code-plan-global' }],
  'cloudflare-ai-gateway': [
    {
      provider: 'cloudflare-ai-gateway',
      rewrite: (id: string) => id.replace(/^google\//, 'google-ai-studio/'),
    },
    {
      provider: 'cloudflare-workers-ai',
      rewrite: (id: string) => `workers-ai/${id}`,
    },
  ],
};

// An agent needs text in, text out and tool calling; image, audio and
// embedding models fail one of these.
const isAgentModel = (model: TModelsDevModel) => {
  const output = model.modalities?.output || [];

  return (
    !!model.tool_call &&
    output.includes('text') &&
    !output.includes('image') &&
    !output.includes('audio')
  );
};

const toEntry = (model: TModelsDevModel): TAiModelCatalogEntry => ({
  agent: isAgentModel(model),
  ...(model.status === 'deprecated' ? { deprecated: true } : {}),
  ...(model.release_date ? { releasedAt: model.release_date } : {}),
  ...(model.reasoning ? { reasoning: true } : {}),
  ...(model.limit?.context ? { contextWindow: model.limit.context } : {}),
});

const loadSource = async (path?: string): Promise<TModelsDevSource> => {
  if (path) {
    return JSON.parse(await readFile(path, 'utf8'));
  }

  const response = await fetch(SOURCE_URL);

  if (!response.ok) {
    throw new Error(`models.dev responded ${response.status}`);
  }

  return response.json();
};

// A retired default would reach every new agent, so it fails the run; an id
// models.dev does not list may just be unindexed, so it only warns.
const checkConfiguredModels = (catalog: TAiModelCatalog) => {
  const errors: string[] = [];
  const warnings: string[] = [];

  for (const provider of AI_AGENT_SUPPORTED_PROVIDERS) {
    const configured = [
      ['default', AI_AGENT_PROVIDER_DEFAULT_MODELS[provider]],
      ...AI_AGENT_RECOMMENDED_MODELS[provider].map((id) => ['recommended', id]),
    ];

    for (const [role, id] of configured) {
      const entry = catalog[provider][id];
      const label = `${provider} ${role} "${id}"`;

      if (!entry) {
        warnings.push(`${label} is not in the catalog`);
      } else if (entry.deprecated || !entry.agent) {
        errors.push(
          `${label} is ${
            entry.deprecated ? 'deprecated' : 'not an agent model'
          }`,
        );
      }
    }
  }

  warnings.forEach((message) => console.warn(`warning: ${message}`));
  errors.forEach((message) => console.error(`error: ${message}`));

  if (errors.length) {
    process.exitCode = 1;
  }
};

const main = async () => {
  const source = await loadSource(process.argv[2]);
  const catalog = {} as TAiModelCatalog;

  for (const key of AI_AGENT_SUPPORTED_PROVIDERS) {
    const entries: Record<string, TAiModelCatalogEntry> = {};

    for (const { provider, rewrite = (id: string) => id } of SOURCES[key]) {
      const models = source[provider]?.models;

      if (!models) {
        throw new Error(`models.dev has no provider "${provider}"`);
      }

      for (const model of Object.values(models)) {
        entries[rewrite(model.id)] = toEntry(model);
      }
    }

    catalog[key] = Object.fromEntries(
      Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)),
    );
  }

  const body = [
    '// Generated by scripts/generateAiModelCatalog.ts from models.dev. Do not edit.',
    "import type { TAiModelCatalog } from './modelCatalog';",
    '',
    `export const AI_MODEL_CATALOG_GENERATED_AT = '${new Date()
      .toISOString()
      .slice(0, 10)}';`,
    '',
    `export const AI_MODEL_CATALOG: TAiModelCatalog = ${JSON.stringify(
      catalog,
      null,
      2,
    )};`,
    '',
  ].join('\n');

  await writeFile(OUTPUT, body);

  checkConfiguredModels(catalog);
};

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
