import type {
  CredentialField,
  CredentialFieldType,
  CredentialTemplate,
} from './types';

const field = (
  key: string,
  label: string,
  type: CredentialFieldType = 'text',
  required = false,
  help?: string,
): CredentialField => ({
  key,
  label,
  type,
  required,
  secret: type === 'password',
  ...(help ? { help } : {}),
});

