// Writes packages/ui/exports.txt: the names plugin UIs import from erxes-ui and the libraries web
// shares with them. Committed and checked by `pnpm check:generated`, so a removal shows in the
// PR's diff instead of as a crash in a plugin built against the old list.
import { readFile, writeFile } from 'node:fs/promises';
import { parseSync } from 'oxc-parser';
import { SHARED } from '../packages/ui/src/federation.ts';

const ui = new URL('../packages/ui/', import.meta.url);
const index = await readFile(new URL('src/index.ts', ui), 'utf8');
const { module, errors } = parseSync('index.ts', index);
const [error] = errors;

if (error) throw new Error(error.message);

const exported = module.staticExports
  .flatMap((statement) => statement.entries)
  .map(({ exportName, isType }) => {
    if (!exportName.name) throw new Error('src/index.ts exports names one by one, not export *');

    return `${isType ? 'type' : 'value'} ${exportName.name}`;
  })
  .toSorted();

const header = [
  '# Generated by tools/ui-exports.ts. Plugin UIs depend on every line: a removed one breaks',
  '# them at runtime. Read .agents/skills/plugin-contract before removing any.',
];

await writeFile(
  new URL('exports.txt', ui),
  [...header, ...SHARED.map((name) => `shared ${name}`), ...exported, ''].join('\n'),
);
